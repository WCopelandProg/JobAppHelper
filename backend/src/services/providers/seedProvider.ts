export const seedProvider: JobProvider = {
  key: JobSourceProvider.SEED,
  displayName: "Curated Sample Listings",

  async fetchJobs(): Promise<NormalizedJob[]> {
    const now = Date.now();
    return SEED_JOBS.map(({ daysAgo, ...job }) => ({
      ...job,
      sourceProvider: JobSourceProvider.SEED,
      postedAt: new Date(now - daysAgo * 24 * 60 * 60 * 1000),
    }));
  },
};
